// Command gorows writes codegen/services.toml's rows from Go's own
// google.golang.org/api module in the module cache (decision 0002): one
// row per package that carries a Discovery document, with Go's package
// path, package name and version and the document's path. Nothing in a
// row is written by hand.
//
//	go run ./codegen/gorows GOMODCACHE VERSION > codegen/services.toml
package main

import (
	"bufio"
	"fmt"
	"io/fs"
	"os"
	"path/filepath"
	"sort"
	"strings"
)

func main() {
	if len(os.Args) != 3 {
		fmt.Fprintln(os.Stderr, "usage: gorows GOMODCACHE VERSION")
		os.Exit(2)
	}
	version := os.Args[2]
	root := filepath.Join(os.Args[1], "google.golang.org", "api@"+version)
	type row struct{ dir, pkg, doc string }
	var rows []row
	err := filepath.WalkDir(root, func(p string, d fs.DirEntry, err error) error {
		if err != nil {
			return err
		}
		// the generator's own test documents are not packages
		if d.IsDir() && (d.Name() == "testdata" || d.Name() == "google-api-go-generator") {
			return filepath.SkipDir
		}
		if d.IsDir() || !strings.HasSuffix(d.Name(), "-api.json") {
			return nil
		}
		dir := filepath.Dir(p)
		rel, _ := filepath.Rel(root, dir)
		gens, _ := filepath.Glob(filepath.Join(dir, "*-gen.go"))
		// large APIs are split over several files (compute-gen.go,
		// compute2-gen.go, ...), all of one package
		if len(gens) == 0 {
			return fmt.Errorf("%s: no -gen.go file", rel)
		}
		sort.Strings(gens)
		pkg, err := packageName(gens[0])
		if err != nil {
			return err
		}
		rows = append(rows, row{filepath.ToSlash(rel), pkg, d.Name()})
		return nil
	})
	if err != nil {
		fmt.Fprintln(os.Stderr, "gorows:", err)
		os.Exit(1)
	}
	sort.Slice(rows, func(i, j int) bool { return rows[i].dir < rows[j].dir })
	fmt.Println("# Generated by codegen/gorows from google.golang.org/api@" + version + "; do not edit.")
	fmt.Println()
	fmt.Printf("go_version = %q\n", version)
	for _, r := range rows {
		fmt.Println()
		fmt.Println("[[service]]")
		fmt.Printf("dir = %q\n", r.dir)
		fmt.Printf("package = %q\n", r.pkg)
		fmt.Printf("doc = %q\n", r.doc)
	}
}

func packageName(file string) (string, error) {
	f, err := os.Open(file)
	if err != nil {
		return "", err
	}
	defer f.Close()
	sc := bufio.NewScanner(f)
	sc.Buffer(make([]byte, 1<<20), 1<<20)
	for sc.Scan() {
		if name, ok := strings.CutPrefix(sc.Text(), "package "); ok {
			return strings.Fields(name)[0], nil
		}
	}
	return "", fmt.Errorf("%s: no package line", file)
}
