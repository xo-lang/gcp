#!/bin/sh
# Fails when files git would commit hold data that must not be public
# (decision 0008): GUIDs other than the all-zero placeholder, keys,
# local home paths, IP addresses outside loopback, the metadata server
# and the documentation ranges, and email addresses. Generated modules
# (their first line names codegen) carry Google's Discovery descriptions
# word for word, Go's own package text, whose examples hold sample
# addresses, ranges and ids; they are left out of those heuristics but
# not of the home path check or of gitleaks, which runs over the whole
# history and every file with the publishing tools' rules.
# Usage: scripts/check-public.sh
set -u
cd "$(dirname "$0")/.."
fail=0
all=$(git ls-files -co --exclude-standard | grep -v -E '^(LICENSE|NOTICE\.md)$')
gen=$(echo "$all" | grep '\.xo$' | while read -r f; do head -1 "$f" | grep -q '^// Code generated by xo-lang/gcp codegen' && echo "$f"; done)
files=$(printf '%s\n%s\n' "$all" "$gen" | sort | uniq -u)

report() {
  echo "check-public: $1 ($(echo "$2" | grep -c .) lines)" >&2
  echo "$2" | head -20 >&2
  fail=1
}

hits=$(echo "$files" | xargs grep -n -I -i -E '[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}' 2>/dev/null | grep -v -E '00000000-0000-0000-0000-000000000000')
[ -n "$hits" ] && report "GUIDs" "$hits"

hits=$(echo "$files" | xargs grep -n -I -E 'AIza[0-9A-Za-z_-]{35}|-----BEGIN [A-Z ]*PRIVATE KEY-----|"private_key_id": *"[0-9a-f]{20}' 2>/dev/null)
[ -n "$hits" ] && report "keys" "$hits"

# a home path of a Mac anywhere; another home path outside generated text
hits=$(echo "$all" | xargs grep -n -I -E '/U''sers/' 2>/dev/null)
[ -n "$hits" ] && report "home paths" "$hits"
hits=$(echo "$files" | xargs grep -n -I -E '/h''ome/[a-z]' 2>/dev/null | grep -v '^scripts/check-public.sh:')
[ -n "$hits" ] && report "home paths" "$hits"

# loopback, the metadata server (169.254.169.254, the documented
# address), the RFC 5737 documentation ranges and 0.0.0.0 are allowed
hits=$(echo "$files" | xargs grep -n -I -E '(^|[^0-9.])([0-9]{1,3}\.){3}[0-9]{1,3}([^0-9.]|$)' 2>/dev/null | grep -v -E '127\.0\.0\.1|169\.254\.169\.254|192\.0\.2\.[0-9]+|198\.51\.100\.[0-9]+|203\.0\.113\.[0-9]+|0\.0\.0\.0' | grep -E '(^|[^0-9.])([0-9]{1,3}\.){3}[0-9]{1,3}([^0-9.]|$)')
[ -n "$hits" ] && report "IP addresses" "$hits"

hits=$(echo "$files" | xargs grep -n -I -E '[A-Za-z0-9._%+-]+@[A-Za-z0-9-]+\.[A-Za-z]{2,}' 2>/dev/null | grep -v -E '@example\.(com|org|net)')
[ -n "$hits" ] && report "email addresses" "$hits"

gl=${GITLEAKS_CONFIG:-../xo-publish-tools/gitleaks.toml}
if [ -f "$gl" ]; then
  cfgdir=$(mktemp -d "${TMPDIR:-/tmp}/gitleaks-gcp.XXXXXX")
  cfg="$cfgdir/gitleaks.toml"
  printf '[extend]\npath = "%s"\n\n' "$(cd "$(dirname "$gl")" && pwd)/$(basename "$gl")" >"$cfg"
  cat scripts/gitleaks-extra.toml >>"$cfg"
  mkdir "$cfgdir/tree"
  git ls-files -co --exclude-standard | rsync -a --files-from=- . "$cfgdir/tree/"
  gitleaks_ok=1
  if git rev-parse -q --verify HEAD >/dev/null; then
    gitleaks git --no-banner -c "$cfg" . >/dev/null 2>&1 || gitleaks_ok=0
  fi
  (cd "$cfgdir/tree" && gitleaks dir --no-banner -c "$cfg" . >/dev/null 2>&1) || gitleaks_ok=0
  if [ $gitleaks_ok = 0 ]; then
    echo "check-public: gitleaks found leaks (run: gitleaks git -c $cfg . and gitleaks dir over the files)" >&2
    fail=1
  fi
  rm -rf "$cfgdir"
else
  echo "check-public: no gitleaks config at $gl; set GITLEAKS_CONFIG" >&2
  fail=1
fi

[ $fail -eq 0 ] && echo "check-public: ok"
exit $fail
